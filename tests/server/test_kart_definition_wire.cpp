// opcode 0x00C0 has one writer now old PartStatPackets kartDef and DriftBoostPackets kartDefinition deleted see server audit item 3
TEST(KartDefinitionWire, VehicleCatalogBytesUnchangedByTheExtraction) {
    std::array<int32_t, 8> defaultParts{};
    std::memcpy(defaultParts.data(), kBlob32, 32);
    std::vector<uint32_t> priceKeys = {100, 200};

    Packet pkt = PacketBuilder::vehicleCatalog(777, "TestModel", defaultParts, priceKeys,
                                                true, "TestDisp", "TestDesc", kStats);

    const auto& body = pkt.payload();
    ASSERT_EQ(body.size(), sizeof(kExpectedVehicleCatalog));
    EXPECT_EQ(0, std::memcmp(body.data(), kExpectedVehicleCatalog, body.size()));
    EXPECT_EQ(pkt.opcode(), 0x00C0);
}

// shared writer alone reproduces the fixed body vehicleCatalog adds only field marshalling and price options
TEST(KartDefinitionWire, SharedWriterMatchesVehicleCatalogFixedPart) {
    KartDefinitionFields f;
    f.visibleFlag = 1;
    f.badge = 0;
    f.kartKey = 777;
    f.unk0c = 0;
    f.vehicleKind = 2;
    f.modelScheme = 1;
    f.unk18 = 0;
    f.requiredLevel = 0;
    f.modelName = "TestModel";
    f.displayNameKey = "TestDisp";
    f.descriptionKey = "TestDesc";
    std::memcpy(f.defaultSkinKeys.data(), kBlob32, 32);
    f.stats = kStats;
    // the pairs stay at the hiding default the captured bytes carry the same value now

    Packet pkt(0x00C0);
    writeKartDefinitionBody(pkt, f);

    // fixedLen is header three strings blob stats and tail before writeCatalogOptions the 149 figure counts option count too
    const size_t fixedLen = KART_DEFINITION_FIXED_BYTES - 4
                           + f.modelName.size() + 1 + f.displayNameKey.size() + 1 + f.descriptionKey.size() + 1;
    ASSERT_EQ(pkt.payload().size(), fixedLen);
    EXPECT_EQ(0, std::memcmp(pkt.payload().data(), kExpectedVehicleCatalog, fixedLen));
}
